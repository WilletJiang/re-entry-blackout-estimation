pub(super) fn chi_square_gate(dof: usize, alpha: f64) -> f64 {
    let key = (dof, (alpha * 1000.0).round() as i32);
    match key {
        (1, 50) => 3.841_459_f64,
        (1, 10) => 6.634_897_f64,
        (1, 1) => 10.827_566_f64,
        (6, 50) => 12.591_587_f64,
        (6, 10) => 16.811_893_f64,
        (6, 1) => 22.457_744_f64,
        (1, _) => 10.827_566_f64,
        (6, _) => 22.457_744_f64,
        _ => {
            let z = match key.1 {
                50 => 1.644_853_626_951_472_2_f64,
                10 => 2.326_347_874_040_840_8_f64,
                1 => 3.090_232_306_167_813_2_f64,
                _ => return 1.0e6,
            };
            let nu = dof as f64;
            if !(nu.is_finite() && nu > 0.0) {
                return 1.0e6;
            }
            let a = 1.0 - 2.0 / (9.0 * nu) + z * (2.0 / (9.0 * nu)).sqrt();
            if a <= 0.0 {
                return 1.0e6;
            }
            nu * a.powi(3)
        }
    }
}
